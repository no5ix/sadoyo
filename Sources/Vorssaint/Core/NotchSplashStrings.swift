    let notifyCancelledBody: String

    /// The interval, as the ruler names its value to a screen reader.
    func intervalLabel(_ seconds: Int) -> String { String(format: everyInterval, seconds) }
    /// The counters under the cache's rate, both named.
    func hitsAndRequests(_ hits: Int, _ requests: Int) -> String {
        String(format: hitsAndRequests, hits, requests)
    }

    func serverAnswered(_ code: Int) -> String { String(format: serverAnswered, code) }
    func noAnswer(_ address: String) -> String { String(format: noAnswer, address) }
    func notifyCompletedBody(_ clock: String) -> String {
        String(format: notifyCompletedBody, clock)
    }
}

