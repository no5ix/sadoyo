import Foundation

struct NotchSplashStrings {
    let title: String
    let description: String
    let start: String
    let stop: String
    let monitoring: String
    let interval: String
    let intervalHint: String
    let everyInterval: String
    let server: String
    let host: String
    let hostHint: String
    let port: String
    let apiKey: String
    let apiKeyHint: String
    /// What the settings say about a key: that there is one, never what it is.
    let apiKeySet: String
    let apiKeyClear: String
    let setupHint: String
    let notMonitoring: String
    let noAddress: String
    let noAnswer: String
    let unreadable: String
    let staleAnswer: String
    let serverAnswered: String
    let decode: String
    let prefill: String
    let ttft: String
    let cacheHitRate: String
    let tokensPerSecond: String
    let timeToFirstToken: String
    let hitsAndRequests: String
    let kvCache: String
    let memoryUsed: String
    let governorLimit: String
    /// The card of the memory's three numbers and the governor's bar.
    let memoryAndKVCache: String
    let utilization: String
    /// The words under the cache's number when the pages run short, and when
    /// the server has begun to spill: the colour is the glance, these are the
    /// explanation.
    let kvScarce: String
    let kvSpilling: String
    /// The card of the last thirty days of tokens.
    let trend: String
    /// "30 days", for the trend's caption.
    let dayCount: String
    /// The caption's two parts, joined as the language joins them.
    let daysAndTokens: String
    let inputSeries: String
    let outputSeries: String
    /// What a chart of a metric says while it has nothing to draw.
    let noMeasurements: String
    /// What the trend says before any day has been measured.
    let noHistoryYet: String
    let taskTime: String
    let inputTokens: String
    let outputTokens: String
    let openSettings: String
    let notifyCompletedTitle: String
    let notifyCompletedBody: String
    /// What the notice says when an activity burst runs out: the endpoint
    /// counts requests, so the app says the activity ended, which is what it
    /// knows, and not that a task was completed, which is what it does not.
    let notifyActivityEndedTitle: String
    let notifyActivityEndedBody: String
    let notifyFailedTitle: String
    let notifyFailedBody: String
    let notifyCancelledTitle: String
    let notifyCancelledBody: String

    /// The interval, as the ruler names its value to a screen reader.
    func intervalLabel(_ seconds: Int) -> String { String(format: everyInterval, seconds) }
    /// The counters under the cache's rate, both named.
    func hitsAndRequests(_ hits: Int, _ requests: Int) -> String {
        String(format: hitsAndRequests, hits, requests)
    }

    func serverAnswered(_ code: Int) -> String { String(format: serverAnswered, code) }
    func noAnswer(_ address: String) -> String { String(format: noAnswer, address) }
    func notifyCompletedBody(_ clock: String) -> String {
        String(format: notifyCompletedBody, clock)
    }
    func notifyActivityEndedBody(_ clock: String) -> String {
        String(format: notifyActivityEndedBody, clock)
    }
    func dayCount(_ days: Int) -> String { String(format: dayCount, days) }
    /// The trend's caption: the period, and the tokens of the period.
    func daysAndTokens(_ days: Int, _ tokens: String) -> String {
        String(format: daysAndTokens, dayCount(days), tokens)
    }
}

